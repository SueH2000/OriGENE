from __future__ import annotations
import os
import json
from pathlib import Path
import numpy as np
import pandas as pd
PROJECT = Path(os.environ.get('ORIGENE_PIPELINE_ROOT', 'epigenetic_snakemake_pipline')).expanduser().resolve()
PREP_ROOT = PROJECT / 'results/06_legacy_preprocessing/singletrack/40000bp'
MODEL_EVAL_ROOT = PROJECT / 'results/07_model_evaluation/reviewer_singletrack'
OUT_ROOT = Path(os.environ.get('ORIGENE_PADDING_ROOT', 'results/exact_padding_3sets')).expanduser().resolve()
EXACT_ROOT = OUT_ROOT / 'exact_lengths'
VALIDATION_ROOT = OUT_ROOT / 'validation'
EXACT_ROOT.mkdir(parents=True, exist_ok=True)
VALIDATION_ROOT.mkdir(parents=True, exist_ok=True)
GENE_SETS = ['original_ng', 'length_set1', 'length_set2']
SOURCES = ['Lung_I_Normal', 'Lung_II_Normal', 'Liver_I_Normal', 'Liver_II_Normal']
REFERENCE_SOURCE = 'Lung_I_Normal'
INPUT_BP = 40000
STEP_WIDTH = 1
ZERO_TOL = 1e-12

def resolve_input_file(value):
    path = Path(str(value)).expanduser()
    old_root = os.environ.get('ORIGENE_LEGACY_PIPELINE_ROOT', '').strip()
    if old_root and path.is_absolute():
        try:
            return PROJECT / path.relative_to(Path(old_root))
        except ValueError:
            pass
    return path if path.is_absolute() else PROJECT / path


def decode_genes(values):
    return np.asarray([x.decode() if isinstance(x, (bytes, np.bytes_)) else str(x) for x in values])

def get_paths(set_id, source):
    base = PREP_ROOT / set_id / source
    model_ready = base / 'model_ready'
    return {'base': base, 'audit': base / 'all_tracks_create_txt_audit.tsv', 'X': model_ready / f'{set_id}_{source}_X.npy', 'y': model_ready / f'{set_id}_{source}_y.npy', 'genes': model_ready / f'{set_id}_{source}_genes.npy'}

def parse_legacy_txt(path, strand):
    """
    Reproduce the Position / Signal representation used by the
    legacy input_target_vectors() function.

    Signal is needed only to validate that replayed support matches
    the actual model-ready array. Padding provenance itself is
    determined by the vectorization branch, not by signal amplitude.
    """
    position = np.array([], dtype=float)
    signal = np.array([], dtype=float)
    firstline = True
    with open(path, 'r') as fh:
        for line in fh:
            if not line.startswith('c'):
                continue
            parts = line.split()
            if len(parts) < 4:
                continue
            start = float(parts[1])
            end = float(parts[2])
            value = float(parts[3])
            if firstline:
                position = np.append(position, start)
                signal = np.append(signal, value)
                position = np.append(position, end)
                firstline = False
            elif int(start) == int(position[-1]):
                position = np.append(position, end)
                signal = np.append(signal, value)
            else:
                signal = np.append(signal, 0.0)
                position = np.append(position, start)
                signal = np.append(signal, value)
                position = np.append(position, end)
    if firstline:
        raise ValueError(f'No usable bedGraph rows in {path}')
    if strand == 'neg':
        Position = np.flipud(np.abs(position[1:]))
        Signal = np.flipud(signal)
    elif strand == 'pos':
        Position = position[:-1]
        Signal = signal
    else:
        raise ValueError(f'Unexpected strand {strand!r}: {path}')
    if len(Position) != len(Signal):
        raise RuntimeError(f'{path}: Position/Signal mismatch {len(Position)} vs {len(Signal)}')
    return (Position, Signal)

def replay_vector_with_mask(Position, Signal):
    """
    Replay the single-track legacy vectorization exactly.

    mask value:
        1 = position generated before terminal padding branch
        0 = position generated by terminal synthetic padding branch

    Internal signal zeros and bedGraph gaps remain mask=1.
    Therefore this mask contains padding provenance rather than
    biological signal presence/absence.
    """
    element = Position
    if len(element) < 2:
        raise ValueError('Position vector contains fewer than two boundaries.')
    uniform_signal = []
    provenance_mask = []
    posindex = 1
    pos = element[0]
    if element[0] > element[1]:
        min_start = element[0]
        max_start = element[0]
        while pos > max_start - INPUT_BP:
            if pos <= element[posindex - 1] and pos > element[posindex]:
                uniform_signal.append(Signal[posindex - 1])
                provenance_mask.append(1.0)
                pos -= STEP_WIDTH
            elif pos <= element[-1]:
                uniform_signal.append(0.0)
                provenance_mask.append(0.0)
                pos -= STEP_WIDTH
            else:
                posindex += 1
                if posindex >= len(element):
                    raise RuntimeError('Negative-strand position-index overflow.')
    else:
        max_start = element[0]
        min_start = element[0]
        while pos < min_start + INPUT_BP:
            if pos >= element[posindex - 1] and pos < element[posindex]:
                uniform_signal.append(Signal[posindex - 1])
                provenance_mask.append(1.0)
                pos += STEP_WIDTH
            elif pos >= element[-1]:
                uniform_signal.append(0.0)
                provenance_mask.append(0.0)
                pos += STEP_WIDTH
            else:
                posindex += 1
                if posindex >= len(element):
                    raise RuntimeError('Positive-strand position-index overflow.')
    uniform_signal = np.asarray(uniform_signal, dtype=np.float64)
    provenance_mask = np.asarray(provenance_mask, dtype=np.float32)
    if len(uniform_signal) != INPUT_BP:
        raise RuntimeError(f'Replayed sequence length {len(uniform_signal)} != {INPUT_BP}')
    if len(provenance_mask) != INPUT_BP:
        raise RuntimeError(f'Replayed mask length {len(provenance_mask)} != {INPUT_BP}')
    zero_idx = np.flatnonzero(provenance_mask == 0)
    if len(zero_idx):
        padding_start = int(zero_idx[0])
        if not np.all(provenance_mask[:padding_start] == 1):
            raise RuntimeError('Non-padding region contains mask=0 before terminal boundary.')
        if not np.all(provenance_mask[padding_start:] == 0):
            raise RuntimeError('Padding mask is not terminal.')
    else:
        padding_start = INPUT_BP
    return (uniform_signal, provenance_mask, padding_start)

def load_source_inputs(set_id, source):
    paths = get_paths(set_id, source)
    for key in ['audit', 'X', 'y', 'genes']:
        if not paths[key].exists():
            raise FileNotFoundError(paths[key])
    audit = pd.read_csv(paths['audit'], sep='\t')
    required_cols = {'gene', 'strand', 'output_file'}
    missing = required_cols - set(audit.columns)
    if missing:
        raise ValueError(f"{paths['audit']} missing columns {sorted(missing)}")
    audit['gene'] = audit['gene'].astype(str)
    audit = audit.drop_duplicates()
    gene_counts = audit.groupby('gene').size()
    duplicated = gene_counts[gene_counts > 1]
    if len(duplicated):
        raise RuntimeError(f'{set_id}/{source}: {len(duplicated)} genes have multiple preprocessing audit rows.')
    audit = audit.set_index('gene')
    genes = decode_genes(np.load(paths['genes'], allow_pickle=True).reshape(-1))
    y = np.load(paths['y'], allow_pickle=True).reshape(-1).astype(int)
    X = np.load(paths['X'], mmap_mode='r')
    if X.shape != (len(genes), INPUT_BP, 1):
        raise RuntimeError(f'{set_id}/{source}: unexpected X shape {X.shape}')
    if len(y) != len(genes):
        raise RuntimeError(f'{set_id}/{source}: labels/genes length mismatch.')
    if len(np.unique(genes)) != len(genes):
        raise RuntimeError(f'{set_id}/{source}: duplicate model-ready genes.')
    missing_genes = [gene for gene in genes if gene not in audit.index]
    if missing_genes:
        raise RuntimeError(f'{set_id}/{source}: {len(missing_genes)} model-ready genes missing from preprocessing audit. Examples: {missing_genes[:10]}')
    return (paths, audit, genes, y, X)

def process_source(set_id, source):
    print('\n' + '-' * 80)
    print(f'{set_id} / {source}')
    print('-' * 80, flush=True)
    paths, audit, genes, y, X = load_source_inputs(set_id, source)
    rows = []
    mask_matrix = np.zeros((len(genes), INPUT_BP, 1), dtype=np.float32)
    for i, gene in enumerate(genes):
        row = audit.loc[gene]
        txt_path = resolve_input_file(row['output_file'])
        if not txt_path.exists():
            raise FileNotFoundError(txt_path)
        Position, Signal = parse_legacy_txt(txt_path, row['strand'])
        replayed, mask, padding_start = replay_vector_with_mask(Position, Signal)
        actual = np.asarray(X[i, :, 0])
        replay_nonzero = np.abs(replayed) > ZERO_TOL
        actual_nonzero = np.abs(actual) > ZERO_TOL
        support_mismatch_bp = int(np.sum(replay_nonzero != actual_nonzero))
        actual_nonzero_in_padding_bp = int(np.sum(actual_nonzero & (mask == 0)))
        valid_length = int(padding_start)
        padding_bp = int(INPUT_BP - valid_length)
        mask_matrix[i, :, 0] = mask
        rows.append({'gene': str(gene), 'label': int(y[i]), 'strand': str(row['strand']), 'valid_length_bp': valid_length, 'padding_start_bp': valid_length, 'padding_bp': padding_bp, 'padding_fraction': padding_bp / float(INPUT_BP), 'support_mismatch_bp': support_mismatch_bp, 'actual_nonzero_in_padding_bp': actual_nonzero_in_padding_bp, 'output_file': str(txt_path)})
    result = pd.DataFrame(rows)
    mismatch_genes = int((result['support_mismatch_bp'] > 0).sum())
    padding_signal_genes = int((result['actual_nonzero_in_padding_bp'] > 0).sum())
    total_mismatch_bp = int(result['support_mismatch_bp'].sum())
    n_padded = int((result['padding_bp'] > 0).sum())
    n_unpadded = int((result['padding_bp'] == 0).sum())
    n_padded_cd = int(((result['label'] == 1) & (result['padding_bp'] > 0)).sum())
    n_padded_ng = int(((result['label'] == 0) & (result['padding_bp'] > 0)).sum())
    print('Genes:', len(result))
    print('Replay/X support mismatch genes:', mismatch_genes)
    print('Total mismatched bp:', total_mismatch_bp)
    print('Genes with actual nonzero inside exact padding:', padding_signal_genes)
    print('Padded genes:', n_padded, f'(CD={n_padded_cd}, NG={n_padded_ng})')
    print('No-padding genes:', n_unpadded)
    if mismatch_genes != 0 or total_mismatch_bp != 0 or padding_signal_genes != 0:
        bad = result[(result['support_mismatch_bp'] > 0) | (result['actual_nonzero_in_padding_bp'] > 0)]
        print('\nFirst failures:')
        print(bad.head(20).to_string(index=False))
        raise RuntimeError(f'{set_id}/{source}: exact replay validation FAILED.')
    source_out = VALIDATION_ROOT / set_id
    source_out.mkdir(parents=True, exist_ok=True)
    result.to_csv(source_out / f'{source}_exact_padding_validation.tsv', sep='\t', index=False)
    np.save(source_out / f'{source}_exact_padding_mask.npy', mask_matrix)
    summary = {'gene_set': set_id, 'source': source, 'N': int(len(result)), 'N_CD': int(np.sum(y == 1)), 'N_NG': int(np.sum(y == 0)), 'N_padded': n_padded, 'N_no_padding': n_unpadded, 'N_padded_CD': n_padded_cd, 'N_padded_NG': n_padded_ng, 'support_mismatch_genes': mismatch_genes, 'support_mismatch_bp': total_mismatch_bp, 'nonzero_in_padding_genes': padding_signal_genes}
    del X
    return (result, mask_matrix, summary)

def process_gene_set(set_id):
    print('\n' + '=' * 90)
    print('GENE SET:', set_id)
    print('=' * 90, flush=True)
    source_results = {}
    source_masks = {}
    summaries = []
    for source in SOURCES:
        result, mask, summary = process_source(set_id, source)
        source_results[source] = result.set_index('gene')
        source_masks[source] = mask
        summaries.append(summary)
    ref = source_results[REFERENCE_SOURCE]
    ref_genes = ref.index.to_numpy()
    comparison_rows = []
    all_identical = True
    for source in SOURCES:
        current = source_results[source]
        missing = set(ref.index) - set(current.index)
        extra = set(current.index) - set(ref.index)
        if missing or extra:
            raise RuntimeError(f'{set_id}/{source}: gene identities differ from reference source.')
        current = current.loc[ref.index]
        diff = ref['valid_length_bp'].to_numpy() != current['valid_length_bp'].to_numpy()
        n_diff = int(np.sum(diff))
        identical = n_diff == 0
        all_identical = all_identical and identical
        print(f'\nExact boundary differences {REFERENCE_SOURCE} vs {source}: {n_diff}/{len(ref)} genes')
        comparison_rows.append({'gene_set': set_id, 'reference_source': REFERENCE_SOURCE, 'source': source, 'N_genes': int(len(ref)), 'N_boundary_differences': n_diff, 'all_boundaries_identical': identical})
    comparison_df = pd.DataFrame(comparison_rows)
    comparison_df.to_csv(VALIDATION_ROOT / set_id / 'cross_source_boundary_comparison.tsv', sep='\t', index=False)
    if not all_identical:
        print('\nWARNING:\nExact padding geometry differs between primary datasets.\nA shared gene-set mask must NOT be used.')
        return (summaries, comparison_df, False)
    exact = ref.reset_index()[['gene', 'label', 'strand', 'valid_length_bp', 'padding_start_bp', 'padding_bp', 'padding_fraction']]
    exact_file = EXACT_ROOT / f'{set_id}_exact_valid_lengths.tsv'
    exact.to_csv(exact_file, sep='\t', index=False)
    ref_mask = source_masks[REFERENCE_SOURCE]
    mask_file = EXACT_ROOT / f'{set_id}_exact_padding_mask.npy'
    np.save(mask_file, ref_mask)
    print('\nPASS:\n  replay/X validation = exact\n  padding contains no actual nonzero signal\n  exact boundaries identical across all four primary datasets')
    print('\nSaved exact geometry:')
    print(' ', exact_file)
    print('Saved exact mask:')
    print(' ', mask_file)
    return (summaries, comparison_df, True)

def main():
    print('=' * 90)
    print('OriGENE exact padding reconstruction')
    print('Method: exact replay of legacy vectorization with padding provenance.')
    print('=' * 90, flush=True)
    all_summaries = []
    comparison_frames = []
    status_rows = []
    for set_id in GENE_SETS:
        try:
            summaries, comparison, shared_geometry_ok = process_gene_set(set_id)
            all_summaries.extend(summaries)
            comparison_frames.append(comparison)
            status_rows.append({'gene_set': set_id, 'status': 'PASS_SHARED_GEOMETRY' if shared_geometry_ok else 'PASS_SOURCE_SPECIFIC_GEOMETRY'})
        except Exception as exc:
            status_rows.append({'gene_set': set_id, 'status': 'FAILED', 'message': repr(exc)})
            pd.DataFrame(status_rows).to_csv(OUT_ROOT / 'exact_padding_status.tsv', sep='\t', index=False)
            raise
    summary_df = pd.DataFrame(all_summaries)
    summary_df.to_csv(OUT_ROOT / 'exact_padding_validation_summary.tsv', sep='\t', index=False)
    if comparison_frames:
        pd.concat(comparison_frames, ignore_index=True).to_csv(OUT_ROOT / 'cross_source_boundary_comparison_all_sets.tsv', sep='\t', index=False)
    status_df = pd.DataFrame(status_rows)
    status_df.to_csv(OUT_ROOT / 'exact_padding_status.tsv', sep='\t', index=False)
    manifest = {'gene_sets': GENE_SETS, 'primary_sources': SOURCES, 'reference_source': REFERENCE_SOURCE, 'input_bp': INPUT_BP, 'padding_definition': 'Positions generated by the terminal zero-padding branch of the replayed legacy vectorization algorithm.', 'important_note': 'Padding boundary is not inferred from the last nonzero H3K4me3 value.'}
    with open(OUT_ROOT / 'exact_padding_manifest.json', 'w') as fh:
        json.dump(manifest, fh, indent=2)
    print('\n' + '=' * 90)
    print('FINAL STATUS')
    print('=' * 90)
    print(status_df.to_string(index=False))
    print('\nValidation summary:')
    print(summary_df[['gene_set', 'source', 'N_padded', 'N_padded_CD', 'N_padded_NG', 'support_mismatch_genes', 'nonzero_in_padding_genes']].to_string(index=False))
if __name__ == '__main__':
    main()
